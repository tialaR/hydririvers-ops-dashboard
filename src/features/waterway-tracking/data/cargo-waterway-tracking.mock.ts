function makeScenario(seed: ScenarioSeed): CargoWaterwayTrackingScenario {
  const labels = corridorLabelMap[seed.corridorId];
  const remainingPercent = 100 - seed.progressPercent;

  return {
    id: seed.cargoId,
    cargoId: seed.cargoId,
    title: seed.title,
    corridorId: seed.corridorId,
    cargoType: seed.cargoType,
    priority: seed.priority,
    status: seed.status,
    riskLevel: seed.riskLevel,
    route: {
      origin: {
        label: 'Origem',
        terminal: `Terminal ${seed.origin}`,
        city: seed.origin,
        state: 'PA',
        description: `Coleta confirmada em ${seed.origin}.`,
      },
      destination: {
        label: 'Destino',
        terminal: `Terminal ${seed.destination}`,
        city: seed.destination,
        state: 'PA',
        description: `Atracacao prevista em ${seed.destination}.`,
      },
      currentDescription: seed.currentDescription,
    },
    vessel: {
      name: seed.vesselName,
      kind: seed.vesselKind,
      operator: 'HydriRivers Ops',
    },
    metrics: {
      progressPercent: seed.progressPercent,
      remainingPercent,
      etaLabel: seed.etaLabel,
      distanceKm: seed.distanceKm,
      signalPercent: seed.signalPercent,
      documentsReadyPercent: seed.documentsReadyPercent,
      estimatedCostBRL: seed.estimatedCostBRL,
      co2SavingsPercent: seed.co2SavingsPercent,
    },
    constraints: [
      {
        type: seed.constraintType,
        severity: seed.riskLevel,
        title: seed.constraintTitle,
        description: seed.constraintDescription,
      },
    ],
    map: {
      primaryRiverLabel: labels.primary,
      secondaryRiverLabel: labels.secondary,
      placeLabels: labels.places,
    },
  };
}

export const CARGO_WATERWAY_TRACKING_SCENARIOS = scenarioSeeds.map(makeScenario);

export const DEFAULT_CARGO_WATERWAY_TRACKING_SCENARIO =
  CARGO_WATERWAY_TRACKING_SCENARIOS[0];

export function getCargoWaterwayTrackingScenario(
  cargoId: string,
): CargoWaterwayTrackingScenario {
  return (
    CARGO_WATERWAY_TRACKING_SCENARIOS.find((scenario) => scenario.cargoId === cargoId) ??
    DEFAULT_CARGO_WATERWAY_TRACKING_SCENARIO
  );
}

export function getCargoWaterwayTrackingScenarioIds(): string[] {
  return CARGO_WATERWAY_TRACKING_SCENARIOS.map((scenario) => scenario.cargoId);
}

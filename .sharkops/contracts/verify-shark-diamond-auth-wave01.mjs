import { readFileSync } from 'node:fs';
import { join } from 'node:path';
const root = process.cwd();
const read = (p) => readFileSync(join(root, p), 'utf8');
const fail = (msg) => { console.error(`[shark-diamond-auth-w01] FAIL: ${msg}`); process.exit(1); };
const constants = read('src/features/auth/domain/auth-constants.ts');
const types = read('src/features/auth/domain/auth.types.ts');
const registry = read('src/shared/mock-data/mock-user-registry.ts');
const register = read('src/app/api/auth/register/route.ts');
const db = read('src/shared/server/mock-db.ts');
const mockMode = read('src/shared/ui/mock-mode/mock-mode.tsx');
if (!constants.includes('ephemeralRegistrationTtlSeconds = 60 * 60 * 24')) fail('24h registration TTL missing');
if (!types.includes("persistenceKind?: 'seed' | 'ephemeral'")) fail('user persistence discriminator missing');
if (!types.includes('expiresAt?: string')) fail('user expiration timestamp missing');
if (!registry.includes("persistenceKind: 'seed'")) fail('seed personas are not marked permanent');
if (!register.includes("persistenceKind: 'ephemeral'")) fail('registered users are not ephemeral');
if (!register.includes('ephemeralRegistrationTtlSeconds * 1000')) fail('register expiration not wired to 24h TTL');
if (!db.includes('pruneExpiredUsers')) fail('expired user pruning missing');
if (!db.includes("user.persistenceKind !== 'ephemeral'")) fail('seed preservation guard missing');
if (mockMode.includes('isAuthPublicShellPathname')) fail('Dev Assist still hidden on auth routes');
console.log('[shark-diamond-auth-w01] PASS');
console.log(' seed personas: permanent');
console.log(' registered mock users: 24h TTL');
console.log(' expired ephemeral users: pruned on read');
console.log(' Dev Assist: available on auth routes when QA UI is enabled');
